#!/usr/bin/env python3
"""Leak check: nothing from data/raw may appear in tracked or trackable files.

  python tools/check_publishable.py                 scan (uses data/raw if present, else tools/token_hashes.txt)
  python tools/check_publishable.py --hashes        force hash mode (what CI uses)
  python tools/check_publishable.py --write-hashes  rebuild tools/token_hashes.txt from data/raw
  python tools/check_publishable.py --root PATH     run against another checkout (testing)

Exit codes: 0 clean, 1 leak found, 2 setup problem.

Hash mode checks single-word tokens only (IPs, MACs, hostnames without spaces, host ids,
site codes). Multi-word hostnames and the DNS suffix are checked in raw mode only.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

IPV4 = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")
MAC = re.compile(r"\b[0-9a-f]{2}(?:[-:][0-9a-f]{2}){5}\b", re.I)
WORD = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.\-]{5,}")
MIN_LEN = 6
MAX_BYTES = 20_000_000

# Files that must name the raw site codes (they map code -> fictional plant).
SITE_EXEMPT = {"config/names.yml", "FACTORY_BUILD.md", "CLAUDE.md"}
SKIP_DIRS = ("data/raw", ".git", "node_modules", ".venv", "__pycache__", "dist", "build")
SKIP_FILES = {"tools/token_hashes.txt"}
# Words that look like tokens but are just words.
STOPWORDS = {
    "unknown", "localhost", "printer", "server", "switch", "gateway", "android",
    "default", "windows", "simatic", "siemens", "station", "controller", "network",
    "managed", "unmanaged", "unsupported", "endpoint", "critical", "noncritical",
}


def norm(s):
    return re.sub(r"^[^A-Za-z0-9]+", "", str(s).strip().lower())


def collect_raw(raw: Path):
    inv = json.loads((raw / "ot_inventory_anonymized.json").read_text(encoding="utf-8"))
    vul = json.loads((raw / "ot_vulnerabilities_anonymized.json").read_text(encoding="utf-8"))

    public = set(STOPWORDS)
    for r in vul:
        for k in ("device_model", "system_manufacturer", "device_firmware", "device_type"):
            public.add(norm(r.get(k, "")))
    for r in inv:
        public.add(norm(r.get("system_manufacturer", "")))
        public.add(norm(r.get("device_type", "")))

    single, multi, sites = set(), set(), set()

    def add(val, bucket=None):
        v = norm(val)
        if len(v) < MIN_LEN or v in public:
            return
        if bucket is None:
            bucket = multi if " " in v else single
        bucket.add(v)

    for r in inv:
        host = r.get("hostname") or ""
        add(host)
        label, _, suffix = norm(host).partition(".")
        if suffix:
            add(label)
            add(suffix, multi)
        add(r.get("current_local_ip", ""))
        add(str(r.get("subnet", "")).split("/")[0])
        disc = r.get("xiot_last_discoverer_hostname") or ""
        add(disc)
        if "-" in disc:
            add(disc.split("-")[0], sites)
        for m in r.get("device_mac_addresses") or []:
            add(m)
    for r in vul:
        add(r.get("host_id", ""))
        add(r.get("hostname", ""))
        add(r.get("local_ip", ""))
        add(r.get("mac_address") or "")
        add(r.get("site_name", ""), sites)

    single -= sites
    return single, multi, sites


def sha(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def write_hashes(path: Path, single, sites):
    lines = ["# sha256 of normalized tokens. T = identifier, S = site code. Generated by check_publishable.py --write-hashes"]
    lines += sorted("T:" + sha(t) for t in single)
    lines += sorted("S:" + sha(t) for t in sites)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_hashes(path: Path):
    t, s = set(), set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("T:"):
            t.add(line[2:])
        elif line.startswith("S:"):
            s.add(line[2:])
    return t, s


def files_to_scan(root: Path):
    try:
        out = subprocess.run(
            ["git", "ls-files", "-co", "--exclude-standard"],
            cwd=root, capture_output=True, text=True, check=True,
        ).stdout.split("\n")
        files = [f for f in out if f]
    except Exception:
        files = [str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()]
    res = []
    for f in files:
        f = f.replace("\\", "/")
        if f in SKIP_FILES:
            continue
        if any(f == d or f.startswith(d + "/") for d in SKIP_DIRS):
            continue
        res.append(f)
    return sorted(set(res))


def candidates(line):
    cands = {norm(m) for m in IPV4.findall(line)}
    cands |= {norm(m) for m in MAC.findall(line)}
    for m in WORD.findall(line):
        n = norm(m)
        cands.add(n)
        for piece in n.split("."):
            if len(piece) >= MIN_LEN:
                cands.add(piece)
    return {c for c in cands if len(c) >= MIN_LEN}


def mask(s):
    return s if len(s) <= 6 else s[:3] + "..." + s[-2:]


def scan(root: Path, single, multi, sites, h_t, h_s, hash_mode):
    hits = []
    for rel in files_to_scan(root):
        p = root / rel
        try:
            if p.stat().st_size > MAX_BYTES:
                continue
            data = p.read_bytes()
        except OSError:
            continue
        if b"\0" in data[:8192]:
            continue
        exempt = rel in SITE_EXEMPT
        for n, line in enumerate(data.decode("utf-8", errors="ignore").splitlines(), 1):
            low = line.lower()
            for c in candidates(line):
                if hash_mode:
                    h = sha(c)
                    if h in h_t:
                        hits.append((rel, n, "identifier", mask(c)))
                    elif h in h_s and not exempt:
                        hits.append((rel, n, "site code", mask(c)))
                else:
                    if c in single:
                        hits.append((rel, n, "identifier", c))
                    elif c in sites and not exempt:
                        hits.append((rel, n, "site code", c))
            if not hash_mode:
                for m in multi:
                    if m in low:
                        hits.append((rel, n, "name", m))
    return hits


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--hashes", action="store_true")
    ap.add_argument("--write-hashes", action="store_true")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    args = ap.parse_args()

    root = Path(args.root).resolve()
    raw = root / "data" / "raw"
    hash_file = root / "tools" / "token_hashes.txt"

    if args.write_hashes:
        if not raw.exists():
            print("data/raw not found, cannot write hashes", file=sys.stderr)
            return 2
        single, multi, sites = collect_raw(raw)
        write_hashes(hash_file, single, sites)
        print(f"wrote {hash_file.relative_to(root)}: {len(single)} identifiers, {len(sites)} site codes "
              f"({len(multi)} multi-word tokens are not hashed)")
        return 0

    hash_mode = args.hashes or not raw.exists()
    if hash_mode:
        if not hash_file.exists():
            print("no data/raw and no tools/token_hashes.txt, nothing to check against", file=sys.stderr)
            return 2
        h_t, h_s = read_hashes(hash_file)
        single = multi = sites = set()
    else:
        single, multi, sites = collect_raw(raw)
        h_t = h_s = set()

    hits = scan(root, single, multi, sites, h_t, h_s, hash_mode)
    mode = "hash" if hash_mode else "raw"
    if hits:
        print(f"LEAK ({mode} mode): {len(hits)} hit(s)")
        for rel, n, kind, tok in hits[:50]:
            print(f"  {rel}:{n}: {kind}: {tok}")
        if len(hits) > 50:
            print(f"  ... and {len(hits) - 50} more")
        return 1
    print(f"clean ({mode} mode)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
